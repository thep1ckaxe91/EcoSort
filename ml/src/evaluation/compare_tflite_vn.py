#!/usr/bin/env python3
"""Run ecosort_v1.tflite and ecosort_v2.tflite on the SAME frozen real-VN test list.

Writes ml/reports/v2/vn_comparison/{comparison.json, predictions.csv, tables.md,
confusion_vn_v1.png, confusion_vn_v2.png}. tables.md holds ready-to-paste tables for
ml/reports/error_analysis_v2.md; observations about the images are still written by a person.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Callable

import numpy as np

REPO_ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(REPO_ROOT / "ml" / "src"))

from ecosort_ml.artifacts import artifact_paths  # noqa: E402
from ecosort_ml.evalkit import (  # noqa: E402
    PREPROCESSING_DESC,
    EvalDataError,
    compare_summaries,
    dump_json,
    load_labels,
    load_rgb_224,
    repo_relative,
    resolve_image,
    sha256_file,
    summarize,
    write_rows,
)
from ecosort_ml.tflite_runner import ContractError, Runner, make_tflite_runner  # noqa: E402
from ecosort_ml.vn_test import check_frozen_vn_test  # noqa: E402


def predict_all(run: Runner, rows: list[dict[str, str]], repo_root: Path) -> tuple[list[int], list[float]]:
    preds: list[int] = []
    confs: list[float] = []
    for r in rows:
        probs = np.asarray(run(load_rgb_224(resolve_image(r, repo_root))))
        preds.append(int(np.argmax(probs)))
        confs.append(float(np.max(probs)))
    return preds, confs


def plot_cm(cm: list[list[int]], labels: list[str], title: str, out: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    arr = np.asarray(cm)
    fig, ax = plt.subplots(figsize=(12, 10))
    im = ax.imshow(arr, interpolation="nearest", cmap="Blues")
    fig.colorbar(im, ax=ax, fraction=0.046, pad=0.04)
    ax.set(xticks=np.arange(len(labels)), yticks=np.arange(len(labels)), xticklabels=labels,
           yticklabels=labels, title=title, ylabel="True Label", xlabel="Predicted Label")
    plt.setp(ax.get_xticklabels(), rotation=45, ha="right", rotation_mode="anchor", fontsize=8)
    plt.setp(ax.get_yticklabels(), fontsize=8)
    thresh = arr.max() / 2.0 if arr.max() > 0 else 0.5
    for i in range(arr.shape[0]):
        for j in range(arr.shape[1]):
            if arr[i, j] > 0:
                ax.text(j, i, str(int(arr[i, j])), ha="center", va="center", fontsize=7,
                        color="white" if arr[i, j] > thresh else "black")
    fig.tight_layout()
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, dpi=150)
    plt.close(fig)


def render_tables(payload: dict[str, object]) -> str:
    s1, s2 = payload["v1"], payload["v2"]  # type: ignore[index]
    lines = [
        "<!-- generated by ml/src/evaluation/compare_tflite_vn.py; do not edit by hand -->",
        f"Test list: `{payload['test_csv']}` · fingerprint `{str(payload['test_fingerprint'])[:16]}` · "
        f"{s1['n']} images / {payload['test_objects']} objects",  # type: ignore[index]
        "",
        "| Model | Correct / total | Top-1 | Macro-F1 (labels present in VN test) |",
        "|---|---|---|---|",
    ]
    for name, s in (("v1", s1), ("v2", s2)):
        lines.append(f"| {name} | {s['correct']}/{s['n']} | {s['top1'] * 100:.2f}% | {s['macro_f1_present_labels']:.4f} |")  # type: ignore[index]
    d_top1 = (s2["top1"] - s1["top1"]) * 100  # type: ignore[index]
    lines += ["", f"Δ top-1 (v2 − v1): {d_top1:+.2f} pp. Macro-F1 label set: "
              + ", ".join(f"`{x}`" for x in s1["macro_f1_label_set"]), ""]  # type: ignore[index]
    lines += ["| Label | Support | v1 correct | v2 correct | v1 recall | v2 recall | Δ pp |", "|---|---|---|---|---|---|---|"]
    for r in payload["per_class_delta"]:  # type: ignore[union-attr]
        lines.append(f"| `{r['label']}` | {r['support']} | {r['v1_correct']} | {r['v2_correct']} | "
                     f"{r['v1_recall'] * 100:.1f}% | {r['v2_recall'] * 100:.1f}% | {r['delta_pp']:+.1f} |")
    for name, s in (("v1", s1), ("v2", s2)):
        lines += ["", f"Top confusions {name} (true → predicted, count / true-class support):", ""]
        for p in s["top_confusions"]:  # type: ignore[index]
            lines.append(f"- `{p['true']}` → `{p['pred']}`: {p['count']}/{p['true_support']}")
    return "\n".join(lines) + "\n"


def compare(
    v1_model: Path,
    v2_model: Path,
    test_csv: Path,
    manifest: Path,
    out_dir: Path,
    splits_dir: Path | None,
    repo_root: Path = REPO_ROOT,
    runner_factory: Callable[[Path], Runner] = make_tflite_runner,
    make_plots: bool = True,
) -> dict[str, object]:
    labels = load_labels()
    rows, man = check_frozen_vn_test(test_csv, manifest, splits_dir, repo_root)
    for m in (v1_model, v2_model):
        if not m.is_file():
            raise EvalDataError(f"Model not found: {m}")
    sha1, sha2 = sha256_file(v1_model), sha256_file(v2_model)
    if sha1 == sha2:
        raise EvalDataError("v1 and v2 model files are identical; nothing to compare.")
    y_true = [int(r["class_index"]) for r in rows]
    p1, c1 = predict_all(runner_factory(v1_model), rows, repo_root)
    p2, c2 = predict_all(runner_factory(v2_model), rows, repo_root)
    s1, s2 = summarize(y_true, p1, labels), summarize(y_true, p2, labels)
    payload: dict[str, object] = {
        "test_csv": repo_relative(test_csv, repo_root),
        "test_fingerprint": man["fingerprint"],
        "test_objects": man["objects"],
        "preprocessing": PREPROCESSING_DESC,
        "models": {
            "v1": {"path": repo_relative(v1_model, repo_root), "sha256": sha1, "bytes": v1_model.stat().st_size},
            "v2": {"path": repo_relative(v2_model, repo_root), "sha256": sha2, "bytes": v2_model.stat().st_size},
        },
        "v1": s1.to_json(labels),
        "v2": s2.to_json(labels),
        "per_class_delta": compare_summaries(s1, s2, labels),
    }
    out_dir.mkdir(parents=True, exist_ok=True)
    dump_json(out_dir / "comparison.json", payload)
    write_rows(
        out_dir / "predictions.csv",
        [
            {"filepath": r["filepath"], "object_id": r["object_id"], "true": labels[t],
             "v1_pred": labels[a], "v1_conf": f"{ca:.4f}", "v2_pred": labels[b], "v2_conf": f"{cb:.4f}"}
            for r, t, a, ca, b, cb in zip(rows, y_true, p1, c1, p2, c2)
        ],
        ["filepath", "object_id", "true", "v1_pred", "v1_conf", "v2_pred", "v2_conf"],
    )
    (out_dir / "tables.md").write_text(render_tables(payload), encoding="utf-8")
    if make_plots:
        for name, s in (("v1", s1), ("v2", s2)):
            plot_cm(s.confusion, labels,
                    f"{name} TFLite on frozen real-VN test (n={s.n}, top-1={s.top1 * 100:.1f}%)",
                    out_dir / f"confusion_vn_{name}.png")
    return payload


def main(argv: list[str] | None = None) -> int:
    v1, v2 = artifact_paths("v1", REPO_ROOT), artifact_paths("v2", REPO_ROOT)
    parser = argparse.ArgumentParser(description="Compare v1 vs v2 TFLite on the frozen real-VN test list")
    parser.add_argument("--v1", type=Path, default=v1.mobile_tflite)
    parser.add_argument("--v2", type=Path, default=v2.mobile_tflite)
    parser.add_argument("--test-csv", type=Path, default=v2.test_vn_csv)
    parser.add_argument("--manifest", type=Path, default=v2.test_vn_manifest)
    parser.add_argument("--splits-dir", type=Path, default=v2.splits_dir)
    parser.add_argument("--out-dir", type=Path, default=v2.vn_comparison_dir)
    args = parser.parse_args(argv)
    try:
        payload = compare(args.v1, args.v2, args.test_csv, args.manifest, args.out_dir, args.splits_dir)
    except (EvalDataError, ContractError) as exc:
        print(f"[FAIL] {exc}")
        return 1
    print(render_tables(payload))
    print(f"[PASS] Wrote comparison to {args.out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
